class Command(BaseCommand):
    help = 'Seed SEO guide pages and articles'

    def handle(self, *args, **options):
        for i, data in enumerate(GUIDES):
            obj, created = GuidePage.objects.update_or_create(
                slug=data['slug'],
                defaults={**data, 'display_order': i, 'is_published': True},
            )
            self.stdout.write(f"guide #{obj.pk} ({'new' if created else 'updated'})")

        for article_data in ARTICLES:
            slug = article_data.pop('slug')
            article, created = Article.objects.update_or_create(
                slug=slug,
                defaults={**article_data, 'is_published': True},
            )
            self.stdout.write(f"article #{article.pk} ({'new' if created else 'updated'})")

        self.stdout.write(self.style.SUCCESS('SEO content seeded.'))
